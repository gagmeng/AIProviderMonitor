  const origMap = new WeakMap();

  function t(lang, key, vars) {
    let s = (lang === 'en' && EN[key] !== undefined) ? EN[key] : key;
    if (vars) for (const k of Object.keys(vars)) s = s.replace('{' + k + '}', vars[k]);
    return s;
  }

  function applyI18n(lang) {
    const en = lang === 'en';
    document.documentElement.lang = en ? 'en' : 'zh-CN';
    // 文本节点（跳过脚本/样式/输入区与用户数据容器）
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
        const p = node.parentElement;
        if (!p) return NodeFilter.FILTER_REJECT;
        const tag = p.tagName;
        if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'TEXTAREA') return NodeFilter.FILTER_REJECT;
        if (p.closest('[data-i18n-skip]')) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    for (const node of nodes) {
      let orig = origMap.get(node);
      if (orig === undefined) { orig = node.nodeValue; origMap.set(node, orig); }
      if (!en) { if (node.nodeValue !== orig) node.nodeValue = orig; continue; }
      const key = orig.trim();
      if (key && EN[key] !== undefined) {
        const nv = orig.replace(key, EN[key]);
        if (node.nodeValue !== nv) node.nodeValue = nv;
      }
    }
    // placeholder / title 属性
    for (const el of document.querySelectorAll('[placeholder]')) {
      if (el.closest('[data-i18n-skip]')) continue;
      if (el.dataset.i18nPh === undefined) el.dataset.i18nPh = el.getAttribute('placeholder') || '';
      const orig = el.dataset.i18nPh;
      const key = orig.trim();
      el.setAttribute('placeholder', en && EN[key] !== undefined ? EN[key] : orig);
    }
    for (const el of document.querySelectorAll('[title]')) {
      if (el.closest('[data-i18n-skip]')) continue;
      if (el.dataset.i18nTitle === undefined) el.dataset.i18nTitle = el.getAttribute('title') || '';
      const orig = el.dataset.i18nTitle;
      const key = orig.trim();
      el.setAttribute('title', en && EN[key] !== undefined ? EN[key] : orig);
    }
  }

  window.aipmi18n = { t, applyI18n, EN };
